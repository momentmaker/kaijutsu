// RenderReport produces the static HTML report from meta +
// benchmark. Pure function — caller writes the result to disk.
//
// baselineSide / challengerSide are the canonical side names for
// the eval shape (Stage 1: with_skill / without_skill; Stage 2
// extends with persona / mode names).
func RenderReport(meta Meta, bench Benchmark, baselineSide, challengerSide string, estimatedCost float64) (string, error) {
	metaJSON, err := json.Marshal(meta)
	if err != nil {
		return "", fmt.Errorf("marshal meta: %w", err)
	}
	benchJSON, err := json.Marshal(bench)
	if err != nil {
		return "", fmt.Errorf("marshal benchmark: %w", err)
	}

	summaryRows := renderSummaryRows(bench, baselineSide, challengerSide)
	drillDown := renderDrillDown(bench, baselineSide, challengerSide)
	actualCost := 0.0
	for _, r := range bench.Results {
		for _, s := range r.Sides {
			actualCost += s.CostUSD
		}
	}

	out := reportHTMLTemplate
	replacements := map[string]string{
		"{{TITLE}}":                  "kaijutsu eval — " + html.EscapeString(bench.SkillName),
		"{{SKILL_NAME}}":             html.EscapeString(bench.SkillName),
		"{{ITERATION}}":              fmt.Sprintf("%d", bench.Iteration),
		"{{TARGET}}":                 html.EscapeString(meta.Target),
		"{{JUDGE}}":                  html.EscapeString(meta.Judge),
		"{{STARTED_AT}}":             html.EscapeString(meta.StartedAt.Format("2006-01-02 15:04:05 MST")),
		"{{TOTAL_EVALS}}":            fmt.Sprintf("%d", bench.TotalEvals),
		"{{SIDES}}":                  fmt.Sprintf("%d", meta.Sides),
		"{{INDETERMINATE}}":          fmt.Sprintf("%d", bench.Indeterminate),
		"{{ESTIMATED_COST}}":         fmt.Sprintf("%.4f", estimatedCost),
		"{{ACTUAL_COST}}":            fmt.Sprintf("%.4f", actualCost),
		"{{SIDE_BASELINE_HEADER}}":   html.EscapeString(baselineSide),
		"{{SIDE_CHALLENGER_HEADER}}": html.EscapeString(challengerSide),
		"{{SUMMARY_ROWS}}":           summaryRows,
		"{{DRILL_DOWN}}":             drillDown,
		"{{JUDGE_TEMPLATE_VER}}":     html.EscapeString(meta.JudgeTemplateVer),
		"{{META_JSON}}":              string(metaJSON),
		"{{BENCHMARK_JSON}}":         string(benchJSON),
	}
	for k, v := range replacements {
		out = strings.ReplaceAll(out, k, v)
	}
	return out, nil
}

// renderSummaryRows produces the per-eval pass/fail row HTML.
func renderSummaryRows(bench Benchmark, baselineSide, challengerSide string) string {
	ids := SortedEvalIDs(bench)
	var b strings.Builder
	for _, id := range ids {
		r := bench.Results[id]
		b.WriteString("<tr><td><a href=\"#eval-")
		b.WriteString(html.EscapeString(id))
		b.WriteString("\">")
		b.WriteString(html.EscapeString(r.Name))
		b.WriteString(" <small>(")
		b.WriteString(html.EscapeString(id))
		b.WriteString(")</small></a></td>")
		b.WriteString("<td>")
		b.WriteString(passFailCell(r.Sides[baselineSide]))
		b.WriteString("</td><td>")
		b.WriteString(passFailCell(r.Sides[challengerSide]))
		b.WriteString("</td></tr>\n")
	}
	return b.String()
}

func passFailCell(s SideResult) string {
	if s.Indeterminate {
		return `<span class="indeterm">indeterminate</span>`
	}
	if s.Pass {
		return `<span class="pass">pass</span>`
	}
	return `<span class="fail">fail</span>`
}

// renderDrillDown produces per-eval blocks with assertion details +
// output snippets.
func renderDrillDown(bench Benchmark, baselineSide, challengerSide string) string {
	ids := SortedEvalIDs(bench)
	var b strings.Builder
	for _, id := range ids {
		r := bench.Results[id]
		b.WriteString("<div class=\"eval-block\" id=\"eval-")
		b.WriteString(html.EscapeString(id))
		b.WriteString("\">\n<h3>")
		b.WriteString(html.EscapeString(r.Name))
		b.WriteString(" <small>(")
		b.WriteString(html.EscapeString(id))
		b.WriteString(")</small></h3>\n")

		// Sides in stable order.
		sideNames := make([]string, 0, len(r.Sides))
		for s := range r.Sides {
			sideNames = append(sideNames, s)
		}
		sort.Strings(sideNames)
		for _, side := range sideNames {
			s := r.Sides[side]
			b.WriteString("<h4>")
			b.WriteString(html.EscapeString(side))
			b.WriteString(" — ")
			b.WriteString(passFailCell(s))
			b.WriteString(fmt.Sprintf(" · %dms · $%.4f</h4>\n", s.DurationMS, s.CostUSD))
			for _, ar := range s.Assertions {
				b.WriteString("<div class=\"assertion\">\n<div class=\"assertion-text\">")
				b.WriteString(html.EscapeString(ar.Assertion))
				b.WriteString("</div>\n<div>")
				b.WriteString(passFailCell(SideResult{Pass: ar.Pass, Indeterminate: ar.Indeterminate}))
				b.WriteString(fmt.Sprintf(" <small>(judge stage %d)</small></div>\n", ar.JudgeStage))
				if ar.Reason != "" {
					b.WriteString("<div class=\"judge-reason\">")
					b.WriteString(html.EscapeString(ar.Reason))
					b.WriteString("</div>\n")
				}
				b.WriteString("</div>\n")
			}
			if s.Output != "" {
				b.WriteString("<details><summary>output</summary><pre>")
				b.WriteString(html.EscapeString(truncateOutput(s.Output, 5000)))
				b.WriteString("</pre></details>\n")
			}
		}
		b.WriteString("</div>\n")
	}
	return b.String()
}

// truncateOutput caps embedded output snippets at maxBytes; longer
// outputs surface a "[truncated, see eval-<id>/<side>/output.txt]"
// marker.
func truncateOutput(s string, maxBytes int) string {
	if len(s) <= maxBytes {
		return s
	}
	return s[:maxBytes] + "\n\n[truncated; see eval-<id>/<side>/output.txt for full text]"
}
